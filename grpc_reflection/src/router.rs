//! src/router.rs
//!
//! This is the API Gateway / Router.
//! It achieves "Dynamic gRPC Transcoding": it accepts standard
//! REST/JSON HTTP traffic
//! from the outside world exactly like a normal web server
//! (e.g. from a browser).
//! It then uses a dynamically loaded schema (via gRPC Server Reflection)
//! to translate
//! that JSON into highly compressed binary Protocol Buffers (gRPC),
//! forwards it to
//! the backend microservice, and then translates the binary response
//! back to JSON.
//!
//! This demonstrates how large tech companies put generic
//! "Envoy-like" proxies in front of gRPC microservices without
//! forcing the proxy
//! to be recompiled every time a microservice changes its API.

use bytes::{BufMut, Bytes, BytesMut};
use clap::Parser;
use http_body_util::{BodyExt, Full, LengthLimitError, Limited};
use hyper::server::conn::http1;
use hyper::service::service_fn;
use hyper::{Method, Request, Response, StatusCode, header};
use hyper_util::client::legacy::Client;
use hyper_util::client::legacy::connect::HttpConnector;
use hyper_util::rt::{TokioExecutor, TokioIo};
use prost::Message;
use prost_reflect::{DescriptorPool, DynamicMessage};
use serde::de::DeserializeSeed;
use std::convert::Infallible;
use std::net::SocketAddr;
use std::sync::Arc;
use std::time::Duration;
use tokio::net::TcpListener;
use tokio::sync::Semaphore;

use tokio_stream::wrappers::ReceiverStream;
use tonic::transport::Endpoint;

const MAX_BODY_BYTES: usize = 1024 * 1024;
const MAX_CONCURRENT_CONNECTIONS: usize = 128;
const CONNECT_TIMEOUT: Duration = Duration::from_secs(5);
const HEADER_READ_TIMEOUT: Duration = Duration::from_secs(10);
const REQUEST_TIMEOUT: Duration = Duration::from_secs(15);
const ACCEPT_ERROR_BACKOFF: Duration = Duration::from_millis(50);

#[derive(Parser, Debug)]
#[clap(author, version, about = "Hardened demo dynamic gRPC reflection HTTP/JSON router")]
struct Cli {
    /// Socket address to listen on (must be loopback unless --allow-non-loopback is set).
    #[clap(long, default_value = "127.0.0.1:8080")]
    listen: SocketAddr,

    /// Allow binding to a non-loopback address (requires --auth-token or PRAECO_ROUTER_AUTH_TOKEN).
    #[clap(long, default_value_t = false)]
    allow_non_loopback: bool,

    /// Target backend gRPC HTTP/2 URL.
    #[clap(long, default_value = "http://[::1]:50051")]
    backend: String,

    /// Optional static Bearer token required on incoming HTTP requests (or env PRAECO_ROUTER_AUTH_TOKEN).
    #[clap(long)]
    auth_token: Option<String>,
}

// Step 1.1: We manually tell rust to include the Reflection code
// generated by build.rs
// so we have a `ServerReflectionClient` available!
pub mod reflection {
    tonic::include_proto!("grpc.reflection.v1");
}
use reflection::server_reflection_client::ServerReflectionClient;
use reflection::{ServerReflectionRequest, server_reflection_request::MessageRequest};

#[tokio::main]
async fn main() -> Result<(), Box<dyn std::error::Error + Send + Sync>> {
    tracing_subscriber::fmt::init();
    let cli = Cli::parse();

    let auth_token = cli
        .auth_token
        .clone()
        .or_else(|| std::env::var("PRAECO_ROUTER_AUTH_TOKEN").ok())
        .filter(|t| !t.trim().is_empty())
        .map(Arc::<str>::from);

    if !cli.listen.ip().is_loopback() && (!cli.allow_non_loopback || auth_token.is_none()) {
        return Err(
            "Refusing to bind demo router on non-loopback address without --allow-non-loopback and Bearer --auth-token / PRAECO_ROUTER_AUTH_TOKEN".into(),
        );
    }

    println!("Router Core Booting...");

    // 1. BUILD THE DYNAMIC SCHEMA POOL VIA NETWORK REFLECTION
    println!(
        "Connecting to microservice at {} to fetch schema...",
        cli.backend
    );

    let endpoint = Endpoint::from_shared(cli.backend.clone())?
        .connect_timeout(CONNECT_TIMEOUT)
        .timeout(REQUEST_TIMEOUT);
    let channel = endpoint.connect().await?;
    let mut reflection_client = ServerReflectionClient::new(channel);

    // 1.3: Ask the server for a list of all services it provides
    let (tx, rx) = tokio::sync::mpsc::channel(1);
    tx.send(ServerReflectionRequest {
        host: String::new(),
        message_request: Some(MessageRequest::ListServices(String::new())),
    })
    .await?;

    let response = reflection_client
        .server_reflection_info(tonic::Request::new(ReceiverStream::new(rx)))
        .await?;
    let mut response_stream = response.into_inner();

    let mut current_services = Vec::new();
    if let Some(res) = response_stream.message().await?
        && let Some(reflection::server_reflection_response::MessageResponse::ListServicesResponse(
            list_res,
        )) = res.message_response
    {
        for service in list_res.service {
            current_services.push(service.name);
        }
    }

    let mut pool = DescriptorPool::new();

    // 1.5: For every service we found, ask for the raw protobuf bytes
    for service_name in current_services {
        if service_name.starts_with("grpc.reflection") {
            continue; // Skip the reflection service itself
        }

        println!("Discovered service via Reflection: {}", service_name);

        let (tx, rx) = tokio::sync::mpsc::channel(1);
        tx.send(ServerReflectionRequest {
            host: String::new(),
            message_request: Some(MessageRequest::FileContainingSymbol(service_name)),
        })
        .await?;

        let response = reflection_client
            .server_reflection_info(tonic::Request::new(ReceiverStream::new(rx)))
            .await?;
        let mut response_stream = response.into_inner();

        if let Some(res) = response_stream.message().await?
            && let Some(
                reflection::server_reflection_response::MessageResponse::FileDescriptorResponse(
                    fd_res,
                ),
            ) = res.message_response
        {
            for fd_bytes in fd_res.file_descriptor_proto {
                let fd_proto = prost::Message::decode(fd_bytes.as_ref())?;
                pool.add_file_descriptor_proto(fd_proto)?;
            }
        }
    }

    let pool = Arc::new(pool);
    println!("Dynamic schema pool built successfully over the network!");

    // 2. PREPARE THE HTTP/2 BACKEND CLIENT
    let mut http_connector = HttpConnector::new();
    http_connector.set_connect_timeout(Some(CONNECT_TIMEOUT));
    let client: Client<HttpConnector, Full<Bytes>> = Client::builder(TokioExecutor::new())
        .http2_only(true)
        .build(http_connector);
    let client = Arc::new(client);
    let backend_url: Arc<str> = Arc::from(cli.backend.trim_end_matches('/'));

    // 3. START THE PUBLIC EDGE ROUTER (HTTP/1.1 REST)
    let listener = TcpListener::bind(cli.listen).await?;
    let conn_semaphore = Arc::new(Semaphore::new(MAX_CONCURRENT_CONNECTIONS));
    println!("Gateway JSON Endpoint listening on http://{}", cli.listen);

    loop {
        let stream = match listener.accept().await {
            Ok((stream, _)) => stream,
            Err(err) => {
                tracing::warn!("Accept error on {}: {}; backing off", cli.listen, err);
                tokio::time::sleep(ACCEPT_ERROR_BACKOFF).await;
                continue;
            }
        };

        let Ok(permit) = conn_semaphore.clone().try_acquire_owned() else {
            tracing::warn!(
                max_connections = MAX_CONCURRENT_CONNECTIONS,
                "Connection limit reached; dropping incoming TCP connection"
            );
            drop(stream);
            continue;
        };

        let io = TokioIo::new(stream);
        let pool = pool.clone();
        let client = client.clone();
        let backend_url = backend_url.clone();
        let auth_token = auth_token.clone();

        tokio::spawn(async move {
            let _permit = permit;
            if let Err(err) = http1::Builder::new()
                .header_read_timeout(HEADER_READ_TIMEOUT)
                .serve_connection(
                    io,
                    service_fn(move |req| {
                        handle_json_to_grpc(
                            req,
                            backend_url.clone(),
                            pool.clone(),
                            client.clone(),
                            auth_token.clone(),
                        )
                    }),
                )
                .await
            {
                tracing::debug!("Error handling HTTP/1.1 connection: {:?}", err);
            }
        });
    }
}

fn error_response(status: StatusCode, msg: impl Into<Bytes>) -> Response<Full<Bytes>> {
    Response::builder()
        .status(status)
        .header(header::CONTENT_TYPE, "text/plain; charset=utf-8")
        .body(Full::new(msg.into()))
        .unwrap_or_else(|_| Response::new(Full::new(Bytes::from_static(b"Internal Error\n"))))
}

fn constant_time_eq_bytes(a: &[u8], b: &[u8]) -> bool {
    if a.len() != b.len() {
        return false;
    }
    let mut diff = 0u8;
    for (x, y) in a.iter().zip(b.iter()) {
        diff |= x ^ y;
    }
    diff == 0
}

/// The core translation engine.
/// Accepts JSON from the user, enforces size/time/auth bounds, dynamically transcodes
/// to binary Protobuf, hits the backend, transcodes back to JSON, and always returns a
/// valid HTTP response instead of aborting the connection on error paths.
async fn handle_json_to_grpc<B>(
    req: Request<B>,
    grpc_backend_url: Arc<str>,
    pool: Arc<DescriptorPool>,
    client: Arc<Client<HttpConnector, Full<Bytes>>>,
    auth_token: Option<Arc<str>>,
) -> Result<Response<Full<Bytes>>, Infallible>
where
    B: hyper::body::Body + Send + 'static,
    B::Data: Send,
    B::Error: Into<Box<dyn std::error::Error + Send + Sync>>,
{
    if let Some(expected_token) = auth_token.as_deref() {
        let provided = req
            .headers()
            .get(header::AUTHORIZATION)
            .and_then(|v| v.to_str().ok())
            .and_then(|s| s.strip_prefix("Bearer "))
            .map(str::trim);
        let valid = provided
            .is_some_and(|tok| constant_time_eq_bytes(tok.as_bytes(), expected_token.as_bytes()));
        if !valid {
            return Ok(error_response(StatusCode::UNAUTHORIZED, "Unauthorized\n"));
        }
    }

    // ------------------------------------
    // STEP 1: ROUTING / DISCOVERY
    // ------------------------------------
    let uri_path = req.uri().path().to_string();
    let path = uri_path.trim_start_matches('/');
    let parts: Vec<&str> = path.split('/').collect();

    if req.method() != Method::POST || parts.len() != 2 || parts[0].is_empty() || parts[1].is_empty()
    {
        return Ok(error_response(
            StatusCode::NOT_FOUND,
            "Please use POST /Fully.Qualified.Service/Method!\n",
        ));
    }

    let service_name = parts[0];
    let method_name = parts[1];

    let method_desc = match pool.get_service_by_name(service_name) {
        Some(s) => match s.methods().find(|m| m.name() == method_name) {
            Some(m) => m,
            None => return Ok(error_response(StatusCode::NOT_FOUND, "Method Not Found\n")),
        },
        None => return Ok(error_response(StatusCode::NOT_FOUND, "Service Not Found\n")),
    };

    if let Some(content_len) = req
        .headers()
        .get(header::CONTENT_LENGTH)
        .and_then(|v| v.to_str().ok())
        .and_then(|s| s.parse::<usize>().ok())
        && content_len > MAX_BODY_BYTES
    {
        return Ok(error_response(
            StatusCode::PAYLOAD_TOO_LARGE,
            "Request body exceeds maximum allowed size\n",
        ));
    }

    let limited_body = Limited::new(req.into_body(), MAX_BODY_BYTES);
    let incoming_body = match tokio::time::timeout(REQUEST_TIMEOUT, limited_body.collect()).await {
        Ok(Ok(collected)) => collected.to_bytes(),
        Ok(Err(err)) => {
            if err.downcast_ref::<LengthLimitError>().is_some() {
                return Ok(error_response(
                    StatusCode::PAYLOAD_TOO_LARGE,
                    "Request body exceeds maximum allowed size\n",
                ));
            }
            return Ok(error_response(
                StatusCode::BAD_REQUEST,
                "Failed to read request body\n",
            ));
        }
        Err(_) => {
            return Ok(error_response(
                StatusCode::REQUEST_TIMEOUT,
                "Timed out reading request body\n",
            ));
        }
    };
    tracing::debug!(body_len = incoming_body.len(), "Router received JSON payload");

    // ------------------------------------
    // STEP 2: TRANSLATE JSON -> PROTOBUF
    // ------------------------------------
    let mut deserializer = serde_json::Deserializer::from_slice(&incoming_body);
    let dynamic_req_msg = match method_desc.input().deserialize(&mut deserializer) {
        Ok(msg) => msg,
        Err(e) => {
            return Ok(error_response(
                StatusCode::BAD_REQUEST,
                format!("Invalid JSON payload: {}\n", e),
            ));
        }
    };

    let mut protobuf_payload = BytesMut::new();
    if let Err(e) = dynamic_req_msg.encode(&mut protobuf_payload) {
        tracing::warn!("Failed to encode protobuf message: {}", e);
        return Ok(error_response(
            StatusCode::BAD_REQUEST,
            "Failed to encode Protobuf request\n",
        ));
    }

    // ------------------------------------
    // STEP 3: CONSTRUCT gRPC FRAMING
    // ------------------------------------
    let Ok(payload_len_u32) = u32::try_from(protobuf_payload.len()) else {
        return Ok(error_response(
            StatusCode::PAYLOAD_TOO_LARGE,
            "Encoded Protobuf payload too large\n",
        ));
    };
    let mut grpc_frame = BytesMut::with_capacity(5 + protobuf_payload.len());
    grpc_frame.put_u8(0); // 0 = Not compressed
    grpc_frame.put_u32(payload_len_u32);
    grpc_frame.put_slice(&protobuf_payload);

    // ------------------------------------
    // STEP 4: SEND TO MICROSERVICE
    // ------------------------------------
    let grpc_uri = format!("{}/{}", grpc_backend_url, path);
    tracing::debug!(uri = %grpc_uri, "Router forwarding gRPC request");
    let grpc_req = match Request::builder()
        .method(Method::POST)
        .uri(&grpc_uri)
        .header(header::CONTENT_TYPE, "application/grpc")
        .header("te", "trailers")
        .body(Full::new(grpc_frame.freeze()))
    {
        Ok(req) => req,
        Err(e) => {
            tracing::warn!("Failed to build upstream gRPC request: {}", e);
            return Ok(error_response(
                StatusCode::INTERNAL_SERVER_ERROR,
                "Failed to construct backend request\n",
            ));
        }
    };

    let mut grpc_res = match tokio::time::timeout(REQUEST_TIMEOUT, client.request(grpc_req)).await {
        Ok(Ok(res)) => res,
        Ok(Err(e)) => {
            tracing::warn!("Upstream gRPC request failed: {}", e);
            return Ok(error_response(
                StatusCode::BAD_GATEWAY,
                "Backend connection failed\n",
            ));
        }
        Err(_) => {
            return Ok(error_response(
                StatusCode::GATEWAY_TIMEOUT,
                "Backend request timed out\n",
            ));
        }
    };

    if grpc_res.status() != StatusCode::OK {
        return Ok(error_response(
            grpc_res.status(),
            format!("Backend Error: {}\n", grpc_res.status()),
        ));
    }

    // ------------------------------------
    // STEP 5: RECEIVE gRPC BINARY
    // ------------------------------------
    let limited_res_body = Limited::new(grpc_res.body_mut(), MAX_BODY_BYTES);
    let collected = match tokio::time::timeout(REQUEST_TIMEOUT, limited_res_body.collect()).await {
        Ok(Ok(c)) => c,
        Ok(Err(err)) => {
            tracing::warn!("Failed reading upstream gRPC response body: {}", err);
            return Ok(error_response(
                StatusCode::BAD_GATEWAY,
                "Invalid or oversized backend response\n",
            ));
        }
        Err(_) => {
            return Ok(error_response(
                StatusCode::GATEWAY_TIMEOUT,
                "Backend response timed out\n",
            ));
        }
    };

    let grpc_status_ok = collected
        .trailers()
        .and_then(|t| t.get("grpc-status"))
        .and_then(|v| v.to_str().ok())
        .is_none_or(|s| s == "0");
    if !grpc_status_ok {
        return Ok(error_response(
            StatusCode::BAD_GATEWAY,
            "Backend gRPC Error\n",
        ));
    }

    let res_body_bytes = collected.to_bytes();
    let raw_protobuf_res = match extract_grpc_frame(&res_body_bytes) {
        Ok(payload) => payload,
        Err(msg) => return Ok(error_response(StatusCode::BAD_GATEWAY, format!("{msg}\n"))),
    };

    // ------------------------------------
    // STEP 6: TRANSLATE PROTOBUF -> JSON
    // ------------------------------------
    let mut dynamic_res_msg = DynamicMessage::new(method_desc.output());
    if let Err(e) = dynamic_res_msg.merge(raw_protobuf_res) {
        return Ok(error_response(
            StatusCode::BAD_GATEWAY,
            format!("Failed to parse Protobuf: {}\n", e),
        ));
    }

    let response_json = match serde_json::to_string(&dynamic_res_msg) {
        Ok(json) => json,
        Err(e) => {
            tracing::warn!("Failed to serialize JSON response: {}", e);
            return Ok(error_response(
                StatusCode::INTERNAL_SERVER_ERROR,
                "Failed to serialize JSON response\n",
            ));
        }
    };
    tracing::debug!(response_len = response_json.len(), "Router sending JSON response");

    Ok(Response::builder()
        .status(StatusCode::OK)
        .header(header::CONTENT_TYPE, "application/json")
        .body(Full::new(Bytes::from(response_json)))
        .unwrap_or_else(|_| error_response(StatusCode::INTERNAL_SERVER_ERROR, "Internal Error\n")))
}

/// Validates a 5-byte gRPC Length-Prefixed-Message header and returns the
/// uncompressed payload slice without panicking on malformed frames.
fn extract_grpc_frame(buf: &[u8]) -> Result<&[u8], &'static str> {
    if buf.len() < 5 {
        return Err("Invalid gRPC Response");
    }
    if buf[0] != 0 {
        return Err("Compressed gRPC responses are not supported");
    }
    let payload_len = u32::from_be_bytes([buf[1], buf[2], buf[3], buf[4]]) as usize;
    let end = 5usize
        .checked_add(payload_len)
        .filter(|&end| end <= buf.len())
        .ok_or("Truncated or malformed gRPC frame")?;
    Ok(&buf[5..end])
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn test_extract_grpc_frame_valid_and_malformed() {
        // Valid 3-byte payload
        let valid = [0u8, 0, 0, 0, 3, 0x0A, 0x0B, 0x0C];
        assert_eq!(extract_grpc_frame(&valid), Ok(&[0x0A, 0x0B, 0x0C][..]));

        // Valid empty payload
        let empty_payload = [0u8, 0, 0, 0, 0];
        assert_eq!(extract_grpc_frame(&empty_payload), Ok(&[][..]));

        // Too short (< 5 bytes)
        assert!(extract_grpc_frame(&[0u8, 0, 0, 1]).is_err());

        // Compressed flag set (byte 0 != 0)
        let compressed = [1u8, 0, 0, 0, 1, 0xAA];
        assert!(extract_grpc_frame(&compressed).is_err());

        // Length exceeds buffer (previously panicked on slice indexing)
        let truncated = [0u8, 0, 0, 0, 10, 0x01, 0x02];
        assert!(extract_grpc_frame(&truncated).is_err());

        // Extreme length u32::MAX (overflow guard)
        let max_len = [0u8, 0xFF, 0xFF, 0xFF, 0xFF, 0x01];
        assert!(extract_grpc_frame(&max_len).is_err());
    }

    #[tokio::test]
    async fn test_router_enforces_auth_limits_and_returns_http_errors() {
        let pool = Arc::new(DescriptorPool::new());
        let client: Arc<Client<HttpConnector, Full<Bytes>>> = Arc::new(
            Client::builder(TokioExecutor::new())
                .http2_only(true)
                .build_http(),
        );
        let backend: Arc<str> = Arc::from("http://[::1]:50051");

        // 1. Bearer auth rejects missing/wrong token with 401
        let req_unauth = Request::builder()
            .method(Method::POST)
            .uri("/system.SystemMetrics/Health")
            .body(Full::new(Bytes::from_static(b"{}")))
            .unwrap();
        let resp_unauth = handle_json_to_grpc(
            req_unauth,
            backend.clone(),
            pool.clone(),
            client.clone(),
            Some(Arc::from("secret-token")),
        )
        .await
        .unwrap();
        assert_eq!(resp_unauth.status(), StatusCode::UNAUTHORIZED);

        // 2. Non-POST / invalid path -> 404
        let req_bad_method = Request::builder()
            .method(Method::GET)
            .uri("/system.SystemMetrics/Health")
            .body(Full::new(Bytes::new()))
            .unwrap();
        let resp_bad_method = handle_json_to_grpc(
            req_bad_method,
            backend.clone(),
            pool.clone(),
            client.clone(),
            None,
        )
        .await
        .unwrap();
        assert_eq!(resp_bad_method.status(), StatusCode::NOT_FOUND);

        // 3. Unknown service -> clean 404 HTTP response (never aborts connection)
        let req_unknown = Request::builder()
            .method(Method::POST)
            .uri("/missing.Service/Call")
            .body(Full::new(Bytes::from_static(b"{}")))
            .unwrap();
        let resp_unknown = handle_json_to_grpc(
            req_unknown,
            backend,
            pool,
            client,
            None,
        )
        .await
        .unwrap();
        assert_eq!(resp_unknown.status(), StatusCode::NOT_FOUND);
    }
}
